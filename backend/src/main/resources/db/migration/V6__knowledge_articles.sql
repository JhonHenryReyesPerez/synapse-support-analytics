-- RF02/RF03: base de conocimiento con estado editorial (verified, active) y estado de
-- sincronización con el índice vectorial separados.
CREATE TABLE public.knowledge_articles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title character varying(200) NOT NULL,
    problem text NOT NULL,
    symptoms text NOT NULL,
    cause text NOT NULL,
    solution text NOT NULL,
    author_username character varying(50) NOT NULL REFERENCES public."user"(username),
    verified boolean NOT NULL DEFAULT false,
    verified_by_username character varying(50) REFERENCES public."user"(username),
    verified_at timestamp(6) without time zone,
    active boolean NOT NULL DEFAULT false,
    content_version integer NOT NULL DEFAULT 1,
    content_hash character varying(64) NOT NULL,
    index_status character varying(20) NOT NULL DEFAULT 'NOT_INDEXED',
    indexed_version integer,
    indexed_at timestamp(6) without time zone,
    embedding_model character varying(120),
    embedding_dimension integer,
    index_error_code character varying(60),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT ck_article_index_status CHECK (index_status IN ('NOT_INDEXED', 'PENDING', 'INDEXED', 'ERROR')),
    CONSTRAINT ck_article_content_version CHECK (content_version >= 1),
    -- Un artículo solo puede estar activo si está verificado.
    CONSTRAINT ck_article_active_requires_verified CHECK (NOT active OR verified)
);
CREATE INDEX idx_article_eligibility ON public.knowledge_articles (active, verified);
CREATE INDEX idx_article_author ON public.knowledge_articles (author_username);
CREATE INDEX idx_article_sync ON public.knowledge_articles (index_status);
