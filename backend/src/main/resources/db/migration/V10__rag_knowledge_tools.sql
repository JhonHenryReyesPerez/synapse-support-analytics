-- Herramientas RAG v2: tablas aditivas; no borra datos históricos.
CREATE TABLE rag_profiles (
 id varchar(40) PRIMARY KEY, name varchar(100) NOT NULL, model varchar(120) NOT NULL,
 dimension integer NOT NULL CHECK (dimension BETWEEN 1 AND 8192), collection_name varchar(80) NOT NULL UNIQUE,
 strategy varchar(20) NOT NULL CHECK (strategy IN ('TEXT','DENSE','HYBRID','RERANK')),
 min_cosine double precision NOT NULL CHECK(min_cosine BETWEEN 0 AND 1), chunk_size integer NOT NULL,
 representation varchar(20) NOT NULL, rerank_model varchar(120), active boolean NOT NULL DEFAULT false,
 created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE rag_article_metadata (
 article_id bigint PRIMARY KEY REFERENCES knowledge_articles(id), platform varchar(80), application varchar(120),
 product_version varchar(80), architecture varchar(40), source_ticket_id bigint REFERENCES tickets(id), source_document_name varchar(200), source_document_hash varchar(64), source_document_pages integer
);
CREATE TABLE rag_embedding_cache (
 cache_key varchar(64) PRIMARY KEY, model varchar(120) NOT NULL, dimension integer NOT NULL,
 vector_json text NOT NULL, created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE rag_index_manifest (
 profile_id varchar(40) NOT NULL REFERENCES rag_profiles(id), point_id varchar(36) NOT NULL,
 article_id bigint NOT NULL REFERENCES knowledge_articles(id), article_version integer NOT NULL,
 content_hash varchar(64) NOT NULL, indexed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(profile_id, point_id)
);
CREATE TABLE rag_search_runs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id varchar(36) NOT NULL UNIQUE,
 actor varchar(50) NOT NULL REFERENCES public."user"(username), query_id bigint REFERENCES assistance_queries(id),
 profile_id varchar(40) NOT NULL REFERENCES rag_profiles(id), question text NOT NULL,
 status varchar(20) NOT NULL, duration_ms bigint NOT NULL, hits_json text NOT NULL, telemetry_json text NOT NULL,
 error_code varchar(60), created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_rag_runs_profile_time ON rag_search_runs(profile_id,created_at);
CREATE INDEX idx_rag_runs_actor ON rag_search_runs(actor,created_at);
CREATE TABLE rag_evaluation_cases (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, question text NOT NULL,
 expected_ids text NOT NULL, expect_no_results boolean NOT NULL, split varchar(20) NOT NULL,
 category varchar(100), notes text, author varchar(50) NOT NULL REFERENCES public."user"(username),
 created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE rag_evaluation_runs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor varchar(50) NOT NULL REFERENCES public."user"(username),
 results_json text NOT NULL, created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE rag_gap_reviews (
 query_id bigint PRIMARY KEY REFERENCES assistance_queries(id), diagnosis varchar(30) NOT NULL,
 notes text, article_id bigint REFERENCES knowledge_articles(id), reviewer varchar(50) NOT NULL REFERENCES public."user"(username),
 updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE assistance_queries ADD COLUMN retrieval_profile varchar(40);
ALTER TABLE assistance_queries ADD COLUMN advanced_json text;
ALTER TABLE assistance_response_sources ALTER COLUMN score DROP NOT NULL;
