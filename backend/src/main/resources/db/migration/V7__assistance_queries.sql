-- RF04, RF05, RF08: consultas al asistente, respuestas y fuentes utilizadas.
-- No hay ON DELETE CASCADE: la evidencia histórica no se borra al eliminar un ticket, un usuario
-- o un artículo (esas entidades tampoco se eliminan físicamente).

CREATE TABLE public.assistance_queries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id bigint NOT NULL REFERENCES public.tickets(id),
    requester_username character varying(50) NOT NULL REFERENCES public."user"(username),
    question text NOT NULL,
    status character varying(20) NOT NULL,
    request_id character varying(36) NOT NULL,
    error_code character varying(60),
    max_results integer NOT NULL,
    min_score double precision NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    retry_of_id bigint REFERENCES public.assistance_queries(id),
    embedding_model character varying(120),
    similarity_metric character varying(30),
    workflow_version character varying(60),
    created_at timestamp(6) without time zone NOT NULL,
    completed_at timestamp(6) without time zone,
    CONSTRAINT uk_assist_query_request UNIQUE (request_id),
    CONSTRAINT ck_assist_query_status CHECK (status IN ('PENDING', 'ANSWERED', 'NO_RESULTS', 'ERROR')),
    -- Una consulta pendiente no tiene fecha de cierre y una terminal siempre la tiene.
    CONSTRAINT ck_assist_query_completed CHECK ((status = 'PENDING') = (completed_at IS NULL)),
    -- El código de error existe solo en ERROR.
    CONSTRAINT ck_assist_query_error CHECK ((status = 'ERROR') = (error_code IS NOT NULL)),
    CONSTRAINT ck_assist_query_attempts CHECK (attempts BETWEEN 0 AND 2)
);
CREATE INDEX idx_assist_query_ticket_created ON public.assistance_queries (ticket_id, created_at, id);
CREATE INDEX idx_assist_query_status_created ON public.assistance_queries (status, created_at);
-- Una sola consulta en proceso por usuario e incidente: evita duplicados por doble envío.
CREATE UNIQUE INDEX uk_assist_query_one_pending ON public.assistance_queries (ticket_id, requester_username)
    WHERE status = 'PENDING';

CREATE TABLE public.assistance_responses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query_id bigint NOT NULL REFERENCES public.assistance_queries(id),
    answer text NOT NULL,
    generation_model character varying(120),
    created_at timestamp(6) without time zone NOT NULL,
    -- Una consulta tiene como máximo una respuesta: un reintento o un resultado tardío no crea otra.
    CONSTRAINT uk_assist_response_query UNIQUE (query_id)
);

CREATE TABLE public.assistance_response_steps (
    response_id bigint NOT NULL REFERENCES public.assistance_responses(id),
    step_order integer NOT NULL,
    step text NOT NULL,
    PRIMARY KEY (response_id, step_order)
);

CREATE TABLE public.assistance_response_sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    response_id bigint NOT NULL REFERENCES public.assistance_responses(id),
    article_id bigint NOT NULL REFERENCES public.knowledge_articles(id),
    article_version integer NOT NULL,
    score double precision NOT NULL,
    source_order integer NOT NULL,
    article_title character varying(200) NOT NULL,
    evidence text NOT NULL,
    content_hash character varying(64) NOT NULL,
    CONSTRAINT uk_assist_source_article UNIQUE (response_id, article_id),
    CONSTRAINT ck_assist_source_version CHECK (article_version >= 1),
    CONSTRAINT ck_assist_source_score CHECK (score BETWEEN -1 AND 1),
    CONSTRAINT ck_assist_source_order CHECK (source_order >= 1)
);
CREATE INDEX idx_assist_source_response ON public.assistance_response_sources (response_id, source_order);
CREATE INDEX idx_assist_source_article ON public.assistance_response_sources (article_id);
