-- B06: la categoría deja de ser un enum con alias y pasa a ser una entidad relacional.
-- También se normaliza la prioridad a una sola representación (BAJA, MEDIA, ALTA, CRITICA).
-- Recuperación: el valor original queda en tickets.category_legacy hasta que una migración
-- posterior lo retire; no se elimina ningún ticket.

CREATE TABLE public.categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(100) NOT NULL,
    description character varying(500),
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT uk_categories_name UNIQUE (name)
);
CREATE UNIQUE INDEX uk_categories_name_lower ON public.categories (lower(name));

INSERT INTO public.categories (name, description) VALUES
    ('Hardware', 'Equipos de cómputo, periféricos e impresoras'),
    ('Software', 'Sistema operativo, instalación y licenciamiento de programas'),
    ('Conectividad', 'Red cableada, Wi-Fi, VPN e Internet'),
    ('Accesos', 'Cuentas, contraseñas y permisos'),
    ('Aplicaciones', 'Fallos de ejecución de aplicaciones institucionales'),
    ('Servicios informáticos', 'Correo, almacenamiento, respaldo y otros servicios'),
    ('Otros', 'Solicitudes que no encajan en las demás categorías');

ALTER TABLE public.tickets ADD COLUMN category_id bigint;

UPDATE public.tickets t
SET category_id = c.id
FROM public.categories c
WHERE c.name = CASE t.category
    WHEN 'HARDWARE' THEN 'Hardware'
    WHEN 'SOFTWARE' THEN 'Software'
    WHEN 'REDES' THEN 'Conectividad'
    WHEN 'NETWORK' THEN 'Conectividad'
    WHEN 'ACCESOS' THEN 'Accesos'
    WHEN 'ACCESS' THEN 'Accesos'
    WHEN 'OTROS' THEN 'Otros'
    WHEN 'OTHER' THEN 'Otros'
END;

-- Ningún ticket puede quedar sin categoría: si aparece un valor no previsto, la migración se detiene.
DO $$
DECLARE pending integer;
BEGIN
    SELECT count(*) INTO pending FROM public.tickets WHERE category_id IS NULL;
    IF pending > 0 THEN
        RAISE EXCEPTION 'V3: % tickets tienen una categoría sin equivalencia; revisar tickets.category', pending;
    END IF;
END $$;

ALTER TABLE public.tickets ALTER COLUMN category_id SET NOT NULL;
ALTER TABLE public.tickets
    ADD CONSTRAINT fk_tickets_category FOREIGN KEY (category_id) REFERENCES public.categories(id);

ALTER TABLE public.tickets DROP CONSTRAINT IF EXISTS tickets_category_check;
ALTER TABLE public.tickets RENAME COLUMN category TO category_legacy;
ALTER TABLE public.tickets ALTER COLUMN category_legacy DROP NOT NULL;

UPDATE public.tickets SET priority = CASE priority
    WHEN 'LOW' THEN 'BAJA'
    WHEN 'MEDIUM' THEN 'MEDIA'
    WHEN 'HIGH' THEN 'ALTA'
    WHEN 'CRITICAL' THEN 'CRITICA'
    ELSE priority
END;
ALTER TABLE public.tickets DROP CONSTRAINT IF EXISTS tickets_priority_check;
ALTER TABLE public.tickets
    ADD CONSTRAINT tickets_priority_check CHECK (priority IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA'));

CREATE INDEX idx_ticket_category ON public.tickets (category_id);
CREATE INDEX idx_ticket_priority ON public.tickets (priority);
CREATE INDEX idx_ticket_created ON public.tickets (created_at, id);
