-- RF08: calificación de la utilidad de una respuesta, de 1 a 5.
CREATE TABLE public.assistance_ratings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    response_id bigint NOT NULL REFERENCES public.assistance_responses(id),
    username character varying(50) NOT NULL REFERENCES public."user"(username),
    score integer NOT NULL,
    comment_text character varying(1000),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    -- Una calificación por usuario y respuesta: repetir la actualiza, no la duplica.
    CONSTRAINT uk_assist_rating_response_user UNIQUE (response_id, username),
    CONSTRAINT ck_assist_rating_score CHECK (score BETWEEN 1 AND 5)
);
